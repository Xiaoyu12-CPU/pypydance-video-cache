"""Inspect Windows icon resources using only the standard library.

This runs both inside the frozen application and in the Linux release publisher.
Matching the actual RT_GROUP_ICON / RT_ICON payloads prevents a stock PyInstaller
icon from passing merely because an ICO file was copied beside the executable.
"""
from __future__ import annotations

import hashlib
import struct


def _unpack(format_: str, data: bytes, offset: int) -> tuple:
    if offset < 0 or offset + struct.calcsize(format_) > len(data):
        raise ValueError("Truncated Windows icon or PE resource structure.")
    return struct.unpack_from(format_, data, offset)


def ico_frames(data: bytes) -> list[dict]:
    """Return each ICO entry and its original encoded image payload."""
    reserved, kind, count = _unpack("<HHH", data, 0)
    if reserved or kind != 1 or not 1 <= count <= 64:
        raise ValueError("Invalid Windows application ICO header.")
    frames = []
    for index in range(count):
        width, height, colors, reserved, planes, bits, size, offset = _unpack(
            "<BBBBHHII", data, 6 + index * 16,
        )
        if reserved or not size or offset < 6 + count * 16 or offset + size > len(data):
            raise ValueError("Invalid Windows application ICO frame.")
        frames.append({
            "width": width or 256, "height": height or 256,
            "colors": colors, "planes": planes, "bits": bits,
            "size": size, "data": data[offset:offset + size],
        })
    return frames


def _pe_resources(data: bytes) -> dict[tuple[int, int, int], bytes]:
    if data[:2] != b"MZ":
        raise ValueError("The executable is not a Windows PE file.")
    pe, = _unpack("<I", data, 0x3C)
    if data[pe:pe + 4] != b"PE\0\0":
        raise ValueError("The executable has no valid Windows PE signature.")
    section_count, = _unpack("<H", data, pe + 6)
    optional_size, = _unpack("<H", data, pe + 20)
    optional = pe + 24
    magic, = _unpack("<H", data, optional)
    if magic not in (0x10B, 0x20B):
        raise ValueError("Unsupported Windows PE optional header.")
    directory_offset = 96 if magic == 0x10B else 112
    if optional_size < directory_offset + 24:
        raise ValueError("The executable has no PE resource data directory.")
    directory_count, = _unpack("<I", data, optional + directory_offset - 4)
    if directory_count < 3:
        raise ValueError("The executable has no PE resource data directory.")
    resource_rva, resource_size = _unpack("<II", data, optional + directory_offset + 16)
    if not resource_rva or not resource_size:
        raise ValueError("The executable has no Windows icon resources.")
    sections = []
    for index in range(section_count):
        offset = optional + optional_size + index * 40
        virtual_size, rva, raw_size, raw_offset = _unpack("<IIII", data, offset + 8)
        sections.append((rva, max(virtual_size, raw_size), raw_offset, raw_size))

    def file_offset(rva: int, size: int) -> int:
        for start, length, offset, raw_size in sections:
            relative = rva - start
            if 0 <= relative < length and relative + size <= raw_size:
                if offset + relative + size <= len(data):
                    return offset + relative
        raise ValueError("A Windows PE resource points outside its file section.")

    base = file_offset(resource_rva, resource_size)
    resources = {}

    def directory(relative: int, path: tuple[int, ...]) -> None:
        if len(path) >= 3 or relative < 0 or relative + 16 > resource_size:
            raise ValueError("Invalid Windows PE resource directory depth or bounds.")
        named, ids = _unpack("<HH", data, base + relative + 12)
        count = named + ids
        if relative + 16 + count * 8 > resource_size:
            raise ValueError("Truncated Windows PE resource directory entries.")
        for index in range(count):
            name, target = _unpack("<II", data, base + relative + 16 + index * 8)
            if name & 0x80000000:
                continue  # Icon resources generated by PyInstaller have numeric IDs.
            if not path and name not in (3, 14):
                continue
            key = path + (name,)
            if target & 0x80000000:
                directory(target & 0x7FFFFFFF, key)
            else:
                if len(key) != 3 or target + 16 > resource_size:
                    raise ValueError("Invalid Windows icon resource data entry.")
                rva, size = _unpack("<II", data, base + target)
                offset = file_offset(rva, size)
                if key in resources:
                    raise ValueError("Duplicate Windows icon resource ID.")
                resources[key] = data[offset:offset + size]

    directory(0, ())
    return resources


def describe_embedded_icon(executable: bytes, expected_ico: bytes) -> dict:
    """Require one complete icon group to match every approved ICO frame."""
    frames = ico_frames(expected_ico)
    resources = _pe_resources(executable)
    groups = [(key, value) for key, value in resources.items() if key[0] == 14]
    if len(groups) != 1:
        raise ValueError("The executable must contain exactly one approved PY icon group.")
    for (_, group_id, language), group in groups:
        reserved, type_, count = _unpack("<HHH", group, 0)
        if reserved or type_ != 1 or count != len(frames) or len(group) != 6 + count * 14:
            continue
        matched = True
        for index, expected in enumerate(frames):
            width, height, colors, reserved, planes, bits, size, image_id = _unpack(
                "<BBBBHHIH", group, 6 + index * 14,
            )
            attributes = (width or 256, height or 256, colors, planes, bits, size)
            original = tuple(expected[key] for key in ("width", "height", "colors", "planes", "bits", "size"))
            image = resources.get((3, image_id, language))
            if image is None:
                candidates = [value for (type_id, id_, _), value in resources.items()
                              if type_id == 3 and id_ == image_id]
                image = candidates[0] if len(candidates) == 1 else None
            if reserved or attributes != original or image != expected["data"]:
                matched = False
                break
        if matched:
            return {
                "ico_sha256": hashlib.sha256(expected_ico).hexdigest(),
                "executable_sha256": hashlib.sha256(executable).hexdigest(),
                "frame_sizes": [[frame["width"], frame["height"]] for frame in frames],
                "frame_count": len(frames), "group_id": group_id, "language": language,
            }
    raise ValueError("The executable does not embed the approved PY application icon.")
